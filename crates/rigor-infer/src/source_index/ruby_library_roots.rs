/// The feature segments that load library root `root`, or `None`.
pub(crate) fn segments_of(root: &str) -> Option<&'static [&'static str]> {
    ROOTS.binary_search_by(|(k, _)| (*k).cmp(root)).ok().map(|i| ROOTS[i].1)
}

