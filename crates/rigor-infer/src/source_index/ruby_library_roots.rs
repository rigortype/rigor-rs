//! Upstream v0.4.6 (#2264 / issue #2174) — `Environment::RubyLibraryRoots`
//! and `RbsLoader#ruby_library_reopen?`.
//!
//! The reference maps each root constant of a library Ruby ships to the
//! feature segments that load it, built at run time from three places: the
//! rbs gem's `stdlib/` tree, the interpreter's `rubylibdir/*.rb`, and the
//! bundled gems' entry files. A required feature counts only when its first
//! segment is one Ruby ships (`RequiredFeatures::SHIPPED_SEGMENTS`). The port
//! cannot read the host's Ruby, so [`ROOTS`] is that map, intersected with
//! `SHIPPED_SEGMENTS`, dumped from the reference environment. Like
//! `UNBUILDABLE_DEFINITIONS` it is environment-dependent and regenerable:
//!
//! ```text
//! ruby -I reference/rigor/lib -e 'require "rigor"; require "rigor/environment/ruby_library_roots"
//!   r = Rigor::Environment::RubyLibraryRoots.shared; sh = Rigor::Environment::RequiredFeatures::SHIPPED_SEGMENTS
//!   r.sort.each { |k, v| s = v.to_a.select { |x| sh.include?(x) }.sort
//!     puts "    (#{k.inspect}, &[#{s.map(&:inspect).join(", ")}])," unless s.empty? }'
//! ```
//!
//! A root missing here only declines less, which can leave a reference
//! decline unported; it can never mint a diagnostic.

