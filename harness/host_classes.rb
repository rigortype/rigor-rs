# frozen_string_literal: true

# Regenerate `crates/rigor-index/src/rbs/host_resolvable.rs` — the constants
# (top-level and nested) the reference's `check` host process resolves at
# analysis time.
# `class_subtype_result` (acceptance.rb) asks `resolve_class(name)`, which
# const-gets a name WITHOUT triggering autoload or const_missing, so a param
# mismatch can only be proven when the ARGUMENT's class name is in this set —
# sig-declared, project-source and vendored-but-unloaded stdlib classes answer
# "maybe" and never fire. Issue rigor-rs#382.
#
# The set is environment-bound: it must be regenerated under the PINNED
# reference runtime (UPSTREAM.md) whenever the pin bumps. Run from the rigor-rs
# repo root:
#
#     ruby harness/host_classes.rb
#
# It loads the same entrypoint the oracle uses (`exe/rigor` → `rigor/cli`),
# drives one real `check` so every lazy `require` the analysis triggers has
# fired, then walks the constant tree with the same rules `resolve_class`
# applies (constants(false), pending autoloads declined, non-Modules skipped).

require "tmpdir"

ROOT = File.expand_path("..", __dir__)
REF = ENV.fetch("REFERENCE_RIGOR_DIR", File.join(ROOT, "reference", "rigor"))

$LOAD_PATH.unshift File.join(REF, "lib")
$LOAD_PATH.unshift File.join(REF, "plugins", "rigor-rbs-inline", "lib")
require "rigor/cli"

Dir.mktmpdir do |dir|
  File.write(File.join(dir, "a.rb"), "x = 1\n")
  Dir.chdir(dir) do
    begin
      Rigor::CLI.start(["check", "--no-cache", "a.rb"])
    rescue SystemExit
      nil
    end
  end
end

resolvable = []
walk = lambda do |mod, prefix, depth|
  return if depth > 5

  mod.constants(false).each do |c|
    next if mod.autoload?(c)

    name = prefix.empty? ? c.to_s : "#{prefix}::#{c}"
    child = begin
      mod.const_get(c, false)
    rescue StandardError, ScriptError
      nil
    end
    next unless child.is_a?(Module)

    resolvable << name
    walk.call(child, name, depth + 1) if child.name == name
  end
end
walk.call(Object, "", 0)

names = resolvable.uniq.sort

out = File.join(ROOT, "crates", "rigor-index", "src", "rbs", "host_resolvable.rs")
File.write(out, <<~RUST)
  //! GENERATED by `harness/host_classes.rb` under the pinned reference runtime —
  //! do not hand-edit. The constant names the reference `check` host resolves
  //! at analysis time: `class_subtype_result` (acceptance.rb) resolves the
  //! argument's class name against the live process via `const_get` (no
  //! autoload, no `const_missing`), so a Disjoint verdict is a proven `no` only
  //! for names in this set; anything else answers `maybe`.
  //!
  //! Regenerate on each pin bump: `ruby harness/host_classes.rb`.

  /// Sorted for `binary_search`.
  pub(crate) const HOST_RESOLVABLE_CLASSES: &[&str] = &[
  #{names.map { |n| "    #{n.dump}," }.join("\n")}
  ];

  /// Whether `name` (`::`-qualified or bare, leading `::` tolerated)
  /// const-resolves in the reference host — the gate inside the reference's
  /// `class_subtype_result`.
  pub(crate) fn host_resolvable_class(name: &str) -> bool {
      let name = name.strip_prefix("::").unwrap_or(name);
      HOST_RESOLVABLE_CLASSES.binary_search(&name).is_ok()
  }
RUST

warn "wrote #{out} (#{names.size} names)"
