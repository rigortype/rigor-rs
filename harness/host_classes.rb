# frozen_string_literal: true

# Regenerate `crates/rigor-index/src/rbs/host_resolvable.rs` — the constants
# (top-level and nested) the reference's `check` host process resolves at
# analysis time, each with its canonical `Module#name` and host ancestor names.
# `class_subtype_result` (acceptance.rb) asks `resolve_class(name)`, which
# const-gets a name WITHOUT triggering autoload or const_missing, so a param
# mismatch can only be proven when the ARGUMENT's class name is in this set —
# sig-declared, project-source and vendored-but-unloaded stdlib classes answer
# "maybe" and never fire. Issue rigor-rs#382.
#
# The verdict itself also rides on the host: when BOTH names resolve the
# reference answers `actual <= target` on the live hierarchy, and when only
# the actual resolves it answers from the actual's `ancestors.map(&:name)`
# (subtype_result_via_ancestors). RBS chains disagree with both — host
# aliases (`Errno::EWOULDBLOCK` IS `Errno::EAGAIN`, `Mutex` IS
# `Thread::Mutex`) and real ancestry (`Gem::MissingSpecError <
# Gem::LoadError`, `Random` includes `Random::Base`) — so each entry also
# carries `Module#name` and `ancestors.filter_map(&:name)`. Issue rigor-rs#809.
#
# The set is environment-bound: it must be regenerated under the PINNED
# reference runtime (UPSTREAM.md) whenever the pin bumps. Run from the rigor-rs
# repo root:
#
#     ruby harness/host_classes.rb
#
# It loads the same entrypoint the oracle uses (`exe/rigor` → `rigor/cli`),
# drives one real `check` so every lazy `require` the analysis triggers has
# fired, then walks the constant tree with the same rules `resolve_class`
# applies (constants(false), pending autoloads declined, non-Modules skipped).

require "tmpdir"

ROOT = File.expand_path("..", __dir__)
REF = ENV.fetch("REFERENCE_RIGOR_DIR", File.join(ROOT, "reference", "rigor"))

$LOAD_PATH.unshift File.join(REF, "lib")
$LOAD_PATH.unshift File.join(REF, "plugins", "rigor-rbs-inline", "lib")
require "rigor/cli"

Dir.mktmpdir do |dir|
  File.write(File.join(dir, "a.rb"), "x = 1\n")
  Dir.chdir(dir) do
    begin
      Rigor::CLI.start(["check", "--no-cache", "a.rb"])
    rescue SystemExit
      nil
    end
  end
end

entries = {}
walk = lambda do |mod, prefix, depth|
  return if depth > 5

  mod.constants(false).each do |c|
    next if mod.autoload?(c)

    name = prefix.empty? ? c.to_s : "#{prefix}::#{c}"
    child = begin
      mod.const_get(c, false)
    rescue StandardError, ScriptError
      nil
    end
    next unless child.is_a?(Module)

    entries[name] ||= begin
      ancestors = child.ancestors.filter_map(&:name)
      {
        canonical: child.name || name,
        ancestors: ancestors,
      }
    rescue StandardError, ScriptError
      { canonical: name, ancestors: [name] }
    end
    walk.call(child, name, depth + 1) if child.name == name
  end
end
walk.call(Object, "", 0)

names = entries.keys.sort

entry_lines = names.map do |n|
  e = entries[n]
  ancestors = e[:ancestors].map(&:dump).join(", ")
  %(    (#{n.dump}, HostClass { canonical: #{e[:canonical].dump}, ancestors: &[#{ancestors}] }),)
end

out = File.join(ROOT, "crates", "rigor-index", "src", "rbs", "host_resolvable.rs")
File.write(out, <<~RUST)
  //! GENERATED by `harness/host_classes.rb` under the pinned reference runtime —
  //! do not hand-edit. The constant names the reference `check` host resolves
  //! at analysis time, with the live-hierarchy facts `class_subtype_result`
  //! (acceptance.rb) reads off them: `resolve_class` const-gets a name WITHOUT
  //! triggering autoload or `const_missing` — only names keyed here resolve at
  //! all — and the verdict is `actual <= target` on the LIVE ancestry
  //! (`canonical`/`ancestors` below), which bends host aliases
  //! (`Errno::EWOULDBLOCK` IS `Errno::EAGAIN`, `Mutex` IS `Thread::Mutex`) and
  //! real hierarchies (`Gem::MissingSpecError < Gem::LoadError`) that RBS
  //! chains disagree with (rigor-rs#809). Anything not keyed answers `maybe`.
  //!
  //! Regenerate on each pin bump: `ruby harness/host_classes.rb`.

  /// One host-resolvable constant's live-hierarchy facts.
  pub(crate) struct HostClass {
      /// `Module#name` — the canonical spelling; host aliases collapse to the
      /// aliased module's own name (`Mutex` → `"Thread::Mutex"`).
      pub canonical: &'static str,
      /// `ancestors.filter_map(&:name)` — the canonical names on the live
      /// ancestor chain, self first. `actual <= target` is exactly
      /// `ancestors.contains(target.canonical)`.
      pub ancestors: &'static [&'static str],
  }

  /// Sorted by name for `binary_search_by`.
  const HOST_CLASSES: &[(&str, HostClass)] = &[
  #{entry_lines.join("\n")}
  ];

  /// The `resolve_class` mirror: the live-hierarchy facts for `name`
  /// (`::`-qualified or bare, leading `::` tolerated) when it const-resolves
  /// in the reference host.
  pub(crate) fn host_class(name: &str) -> Option<&'static HostClass> {
      let name = name.strip_prefix("::").unwrap_or(name);
      HOST_CLASSES
          .binary_search_by(|(n, _)| n.cmp(&name))
          .ok()
          .map(|i| &HOST_CLASSES[i].1)
  }

  /// Whether `name` (`::`-qualified or bare, leading `::` tolerated)
  /// const-resolves in the reference host — the gate inside the reference's
  /// `class_subtype_result`.
  pub(crate) fn host_resolvable_class(name: &str) -> bool {
      host_class(name).is_some()
  }
RUST

warn "wrote #{out} (#{names.size} names)"
